"""The early scoreboard's page (LP-17f; the grading method's section 14): writes
docs/grading/scoreboard.md from the results store (scoreboard/) and the repository's packs
(packs/, never `MENDARI_PACKS_PATH` or the registry cache) alone, so its bytes depend only on the
repository. It shows the current results of public sets (`results_store.heads`; a hidden set's
result, LP-17k, is not shown here) one table per pack and set (`scoreboard.board`,
`render.scoreboard_markdown`): the scope statement, the insufficient-evidence banner where it
applies, the arms as measured, "not measured" or "not applicable", and the marks "unsigned",
"method draft, not in effect" and "stale after DATE" (or why it is stale); then each superseded
result, with the one that superseded it. No Rank column, no bare percentage.

It also writes the scores web/index.html shows (LP-17g), between its two marker comments: the
Patient Inbox Router's public `test` set from the same board, every arm, a measured entry's
figures as k of n with their intervals, the insufficient-evidence banner, and every other arm
"not measured" or "not applicable". A remote model, and a configuration that calls one (a
variant's name, `rules_and_jev`, can name its provider), is written only once its provider
type's disclosure is stated; until then an entry's figures are withheld too. web/ is deployed
by hand, after gate G1-2's patent-decision (attested and deployed 2026-11-07).

    uv run python scripts/scoreboard_page.py           # write the page and the site's scores
    uv run python scripts/scoreboard_page.py --check   # exit 1 when either is not the store's

CI's `reference-pack` job runs --check before scripts/build-reference-pack.sh, which writes the
page again (a pack change makes its results stale, and the page says so).
"""

from __future__ import annotations

import argparse
import html
import sys
from collections.abc import Callable, Container, Mapping, Sequence
from pathlib import Path
from typing import Any

from mendari.core.pack import Pack
from mendari.evals import arms, method, results_store, runs, scoreboard
from mendari.evals.render import scoreboard_markdown, shown

ROOT = Path(__file__).resolve().parent.parent
STORE = ROOT / results_store.ROOT
PACKS = ROOT / "packs"
PAGE = ROOT / "docs" / "grading" / "scoreboard.md"
TITLE = "# Scoreboard (public sets)"
GENERATED = (
    "<!-- Generated by scripts/scoreboard_page.py from the results store (scoreboard/): run it "
    "again rather than edit this page. -->"
)
# The public page's scores (web/index.html), between these two lines; the rest of the page is
# written by hand.
WEB = ROOT / "web" / "index.html"
WEB_PACK, WEB_SET = "mendari/patient-inbox-router", "test"
WEB_BEGIN = (
    "<!-- Generated by scripts/scoreboard_page.py from the results store (scoreboard/), down to "
    "the closing comment: run it again rather than edit these lines. -->"
)
WEB_END = "<!-- End of the scores scripts/scoreboard_page.py generates. -->"
WEB_INDENT = " " * 6  # inside <section id="scores">
# Sites' own evaluations (LP-22, ADR-0017): shown on the Hub beside each pack, never here. The
# page is made from the repository alone, so it names no registry's address (conflict 6 of
# notes/lp22-plan.md: the sentence, and no link).
SITE_EVIDENCE = (
    "Sites' own evaluations of a pack, shared as signed counts, are shown on the Hub, in each "
    "pack's Site evidence section. None of them is on this page, in any table or any grade: "
    "sites choose their own cases, and a ticket binds a dataset before its run, not how its "
    "cases were chosen."
)
# Written in place of a configuration that calls a remote type whose disclosure is not stated.
WITHHELD = "withheld: disclosure pending"


def repository_pack(ref: str) -> Pack:
    """The pack `ref` names, from the repository's packs/ alone (`maintained_pack`)."""
    return results_store.maintained_pack(ref, PACKS)


def _public_results(store: results_store.Store) -> dict[str, results_store.Held]:
    """The store's results of public sets: a hidden set's result (LP-17k) is on neither the page
    nor the site."""
    return {name: found for name, found in store.results().items() if not found.is_hidden}


def _board(store: results_store.Store, packs: Callable[[str], Pack]) -> dict[str, Any]:
    """The board of the store's current results of public sets, against the packs they are of
    and the store's canaries: the page's and the site's, so both publish an entry by the same
    rule."""
    current = results_store.heads(_public_results(store))
    of = {found.pack_id: scoreboard.Current.of(packs(found.pack_id)) for found in current.values()}
    # Published against the disclosures file as it is now, never only the statements a result
    # was stored with: a statement taken out or rewritten since hides the figures.
    return scoreboard.board(
        [found.result for found in current.values()],
        of,
        list(store.canaries().values()),
        disclosures=store.disclosures(),
    )


def page(store: results_store.Store, packs: Callable[[str], Pack] = repository_pack) -> str:
    """The page's text: from the store's results of public sets and the packs they are of,
    nothing else. A hidden set's result (LP-17k) is not on this page."""
    results = _public_results(store)
    current = results_store.heads(results)
    later = results_store.superseded(results)
    board = _board(store, packs)
    canaries = store.canaries()
    disclosures = store.disclosures()
    signed = sum(found.signed for found in current.values())
    lines = [
        TITLE,
        "",
        GENERATED,
        "",
        "The early scoreboard (stage 3 of the [grading method](method-1.0.md), section 14): every "
        "local configuration of each reference pack, on each of its public scoring sets (its "
        "`test` set, its enriched set and that set's holdout), and each remote configuration "
        "run by hand as its arm's declared one (section 10). This page is generated from the "
        "results store, `scoreboard/` in the repository, and from nothing else, so the same "
        "store gives the same page ([running and checking the "
        "scoreboard](../operations/scoreboard.md)).",
        "",
        '!!! warning "Engineering evaluation, not clinical validation"',
        "    Every set here is public: it is in the repository and in the package, so anything "
        "can be tuned to it. Each table is a regression check, not a ranking. No figure orders "
        "its columns, and nothing here is graded: grades are given only on frozen hidden sets.",
        "",
        SITE_EVIDENCE,
        "",
        f"- **{_counted(len(current), 'current result')}** "
        f"({_counted(len(later), 'superseded result')} listed at the end), "
        f'{signed} signed. A result reads "{scoreboard.UNSIGNED}" until the owner signs it '
        "([verifying a result](verifying.md)).",
        _draft_legend(),
        "- **Stale:** each result shows the day it goes stale, "
        f"{method.STALE_AFTER_DAYS} days after it was measured, "
        'as "stale after DATE". It reads "stale: pack changed", "stale: set changed" or "stale: '
        'method changed" when the pack, the set or the method is no longer the one it was '
        "measured on. A stale result is run again, never edited, and the new one supersedes it.",
        "- **Insufficient evidence:** a table whose critical label has fewer distinct positives "
        "than the method's minimum carries the banner, naming each such label.",
        "- **Not measured:** an arm, or a configuration of a measured arm, that no result covers "
        "yet.",
        "- **Remote configurations** (section 10) are run by hand, never in CI, as their arm's "
        "declared configuration (`scoreboard/declared/`), in 3 to 5 replicates: replicate 1 is "
        "the headline, with the case flip rate between any two replicates and the spread of each "
        "figure in its column (not its subgroups', which move only where cases flip). A result "
        "keeps the statements `scoreboard/disclosures.json` held for each remote provider type "
        "it calls when it was stored. Its figures are shown only when each had one then, and "
        "the file still holds it: otherwise it reads "
        f'"{scoreboard.DISCLOSURE_PENDING}", with its scope shown and its figures not, until it '
        "is run again (`--again`). A local configuration is deterministic: one replicate, no "
        "flips.",
        f'- **"{scoreboard.STALE_MODEL}":** a result whose replicates reported more than one '
        "model of a type, or one for which a later run of the same model type reports another "
        "model: a result or a canary, of any pack or configuration, the same day included.",
        "- **Canaries** (section 12), run by hand: a seeded draw of 30 `test` cases. One that "
        f'shows drift marks "{scoreboard.STALE_DRIFT}" the remote results of its pack\'s arm '
        "measured before it (on any set), and those measured no later than the replicates it "
        "was compared with.",
        "",
        scoreboard_markdown(board).rstrip("\n"),
        "",
        "## Canaries",
        "",
        *_canary_lines(canaries, results, disclosures),
        "",
        "## Superseded results",
        "",
    ]
    if not later:
        lines.append("None yet: no stored result has been superseded.")
    else:
        lines += [
            "Each stays in the store, as it was stored, and is no longer shown above.",
            "",
            "| Result | Superseded by | Pack, set and configuration | Measured on |",
            "|---|---|---|---|",
        ]
        for name, by in sorted(later.items()):
            found = results.get(name)  # the store's check refuses a link to no stored result
            what = ("not stored", "") if found is None else (found.shown, found.measured_on)
            lines.append(f"| `{name[:16]}` | `{by[:16]}` | {what[0]} | {what[1]} |")
    return "\n".join(lines) + "\n"


def _canary_lines(
    canaries: dict[str, dict[str, Any]],
    results: dict[str, results_store.Held],
    disclosures: runs.Disclosures | None,
) -> list[str]:
    """Each stored canary: what it was run on and against, and what it found. Its flip rate is
    shown only when the result it was compared with is published (`scoreboard.published`)."""
    if not canaries:
        return ["None yet: no canary has been run."]
    lines = [
        "| Canary | Pack and configuration | Measured on | Against | Flip rate | Marks |",
        "|---|---|---|---|---|---|",
    ]
    for name, found in sorted(canaries.items(), key=lambda item: (item[1]["measured_on"], item[0])):
        against = str(found["against"]["result"]).removeprefix("sha256:")
        held = results.get(against)
        shown_rate = (
            f"{shown(found['flip_rate'])} of drawn cases"
            if held is not None and scoreboard.published(held.result, disclosures)
            else scoreboard.DISCLOSURE_PENDING
        )
        marks = [
            mark
            for mark, on in (
                (scoreboard.STALE_DRIFT, found["drift"]),
                (scoreboard.STALE_MODEL, found["another_model"]),
            )
            if on
        ]
        providers = results_store.written(found["configuration"]["providers"])
        lines.append(
            f"| `{name[:16]}` | {found['pack']['id']} `{providers}` | {found['measured_on']} | "
            f"`{against[:16]}` | {shown_rate} | {'; '.join(marks) or 'none'} |"
        )
    return lines


def _counted(count: int, what: str) -> str:
    return f"{count} {what}{'' if count == 1 else 's'}"


def _draft_legend() -> str:
    """What the draft mark means as the method stands: a result keeps the mark it was measured
    with, so once the owner sets the effective date (`method.EFFECTIVE`, the runbook's step 4)
    the mark is on the results measured before that day."""
    if method.EFFECTIVE is None:
        meaning = "the method has no effective date yet."
    else:
        meaning = f"measured before the method's effective date, {method.EFFECTIVE.isoformat()}."
    return f'- **"{scoreboard.DRAFT}":** {meaning}'


def web_scores(store: results_store.Store, packs: Callable[[str], Pack] = repository_pack) -> str:
    """The scores web/index.html shows between `WEB_BEGIN` and `WEB_END`, those lines included:
    the board's table of `WEB_PACK` on `WEB_SET`, as the page's. One row per entry (its arm, its
    configuration, the models a stated disclosure names, its marks, then accuracy, automation,
    false automation and each critical label's detection, each k of n with its exact 95%
    interval), one per configuration of a measured arm not measured yet, and one per arm with no
    entry ("not measured" or "not applicable"), in the arms' order. A configuration that calls a
    remote type whose disclosure is not stated is not written (`_arm_rows`): an entry of one
    names neither its configuration nor its models and shows "not published: disclosure
    pending" in place of its figures. No row is marked best, and nothing is ranked."""
    table = next(
        (t for t in _board(store, packs)["tables"] if (t["pack"], t["set"]) == (WEB_PACK, WEB_SET)),
        None,
    )
    if table is None:
        raise SystemExit(
            f"error: the results store holds no current result of {WEB_PACK} on {WEB_SET}"
        )
    esc = html.escape
    entries = table["entries"]
    scopes = [item["entry"]["scope"] for item in entries]
    pairs = list(
        dict.fromkeys(
            (c["question"], c["label"])
            for item in entries
            for c in item["entry"]["figures"]["critical"]
        )
    )
    width = 3 + len(pairs)
    name = packs(WEB_PACK).manifest.name
    sets = [s["set"] for s in scopes]
    sizes = _each(f"{s['n']} cases, {s['distinct_inputs']} distinct inputs" for s in sets)
    about = (
        f"Public set <code>{esc(WEB_SET)}</code> · {esc(sizes)} · "
        f"pack {esc(_each(s['pack']['version'] for s in scopes))} · "
        f"measured {esc(_each(s['measured_on'] for s in scopes))}"
    )
    lines = [
        WEB_BEGIN,
        '<div class="board">',
        '  <div class="board-head">',
        f"    <h3>{esc(name)}</h3>",
        f'    <span class="muted small">{about}</span>',
        f'    <p class="synthetic">{esc(_each(s["status"] for s in scopes))}</p>',
        "  </div>",
        f'  <p class="board-note">{esc(_sentence(table["ranking"]["reason"]))} '
        f"{esc(_sentence(table['evaluation']))}</p>",
    ]
    if table["banner"] is not None:
        short = dict.fromkeys(
            f"{s['question']}={s['label']} has {s['positives']} distinct positives here (the "
            f"grading method needs {s['needed']})"
            for s in table["banner"]["short"]
        )
        lines.append(
            f'  <p class="board-note caution">Insufficient evidence: {esc("; ".join(short))}, so '
            "no figure on this set can show that a recall floor is met.</p>"
        )
    head = [
        '<th scope="col">Configuration</th>',
        '<th scope="col" class="num">Correct</th>',
        '<th scope="col" class="num"><span class="full">Automated</span>'
        '<span class="abbr" aria-hidden="true">Auto</span></th>',
        '<th scope="col" class="num">Unsafe</th>',
        *(f'<th scope="col" class="num">{esc(_caught(label))}</th>' for _, label in pairs),
    ]
    lines += [
        f'  <div class="scroll" role="region" aria-label="Scores for the {esc(name)} on its public '
        f'{esc(WEB_SET)} set" tabindex="0">',
        "    <table>",
        "      <thead>",
        f"        <tr>{''.join(head)}</tr>",
        "      </thead>",
        "      <tbody>",
    ]
    named = nameable(packs(WEB_PACK), store.disclosures())
    for arm in table["arms"]:
        lines += [f"        {row}" for row in _arm_rows(table, arm, pairs, width, named)]
    lines += [
        "      </tbody>",
        "    </table>",
        "  </div>",
        '  <p class="board-note muted small">Correct is over the labelled cases, automated over '
        "every case, unsafe (a case the pack automated and got wrong) over the labelled cases, "
        "and caught over the critical label's positives. Not measured: no result is stored for "
        "it yet.</p>",
        "</div>",
        WEB_END,
    ]
    return "\n".join(f"{WEB_INDENT}{line}" for line in lines) + "\n"


def nameable(pack: Pack, disclosures: runs.Disclosures | None) -> frozenset[str]:
    """The configurations of `pack` the site may write, `slot=variant` with the slots sorted as
    the board writes them: each that calls no remote type, or only types whose disclosure is
    stated. A variant's name can name its provider (`rules_and_jev`), so no other is written."""
    held = {} if disclosures is None else disclosures.statements
    stated = {kind for kind, statement in held.items() if statement is not None}
    return frozenset(
        ",".join(f"{slot}={each.providers[slot]}" for slot in sorted(each.providers))
        for arm in arms.arms(pack).values()
        for each in arm.configurations
        if set(each.remote_types) <= stated
    )


def _arm_rows(
    table: Mapping[str, Any],
    arm: Mapping[str, Any],
    pairs: Sequence[tuple[str, str]],
    width: int,
    named: Container[str],
) -> list[str]:
    """The rows of one arm of `table`: each of its entries, each of its configurations not
    measured yet, and its status when it has no entry. A configuration not measured yet that is
    not `named` is not written: those are counted in one row, "withheld"."""
    rows = [
        _web_entry(item, pairs, width)
        for item in table["entries"]
        if item["entry"]["arm"] == arm["arm"]
    ]
    missing = [item["configuration"] for item in table["not_measured"] if item["arm"] == arm["arm"]]
    rows += [
        _gap(arm["name"], _configuration(label), scoreboard.NOT_MEASURED, width)
        for label in missing
        if label in named
    ]
    withheld = sum(label not in named for label in missing)
    if withheld:
        detail = f"{_counted(withheld, 'configuration')} {WITHHELD}"
        rows.append(_gap(arm["name"], detail, scoreboard.NOT_MEASURED, width))
    if arm["status"] != scoreboard.MEASURED:
        rows.append(_gap(arm["name"], None, arm["status"], width))
    return rows


def _web_entry(item: Mapping[str, Any], pairs: Sequence[tuple[str, str]], width: int) -> str:
    """An entry's row. One whose disclosure is pending names neither its configuration nor its
    models, and its figures are withheld."""
    esc = html.escape
    found = item["entry"]
    spans = [
        _configuration(item["configuration"]) if item["published"] else f"configuration {WITHHELD}"
    ]
    by_type = found["scope"]["models"]["by_type"]
    if item["published"] and by_type:  # a stated disclosure: the models as reported
        spans.append("; ".join(f"{kind}: {', '.join(models)}" for kind, models in by_type.items()))
    spans.append("; ".join(item["marks"]))
    head = f'<th scope="row">{esc(item["arm_name"])} ' + "".join(
        f"<span>{esc(span)}</span>" for span in spans
    )
    if not item["published"]:
        return (
            f'<tr>{head}</th><td colspan="{width}" class="muted">'
            f"{scoreboard.DISCLOSURE_PENDING}</td></tr>"
        )
    figures = found["figures"]
    critical = {(c["question"], c["label"]): c["detected"] for c in figures["critical"]}
    cells = [
        figures["accuracy"],
        figures["automation"],
        figures["false_automation"],
        *(critical.get(pair) for pair in pairs),
    ]
    return f"<tr>{head}</th>" + "".join(_figure_cell(cell) for cell in cells) + "</tr>"


def _gap(arm: str, detail: str | None, status: str, width: int) -> str:
    """The row of an arm, or of configurations of it (`detail`, as written), that no entry here
    covers."""
    esc = html.escape
    written = "" if detail is None else f" <span>{esc(detail)}</span>"
    return (
        f'<tr><th scope="row">{esc(arm)}{written}</th>'
        f'<td colspan="{width}" class="muted">{esc(status)}</td></tr>'
    )


def _figure_cell(figure: Mapping[str, Any] | None) -> str:
    """k of n with its interval beneath it, as `render.shown` writes them."""
    count, _, interval = shown(figure).partition(" [")
    below = f' <span class="interval">[{html.escape(interval)}</span>' if interval else ""
    return f'<td class="num">{html.escape(count)}{below}</td>'


def _configuration(written: str) -> str:
    """`slot=variant` pairs, as the board writes them, spaced for reading."""
    return written.replace(",", ", ")


def _caught(label: str) -> str:
    return f"{label.replace('_', ' ').capitalize()} caught"


def _sentence(text: str) -> str:
    return text[:1].upper() + text[1:] + "."


def _each(values: Any) -> str:
    """One value, or each of several, in order."""
    return " or ".join(dict.fromkeys(str(value) for value in values))


def with_scores(site: str, scores: str) -> str:
    """`site` (web/index.html's text) with `scores` in place of what its markers hold."""
    begin, end = site.find(WEB_INDENT + WEB_BEGIN), site.find(WEB_END)
    if begin < 0 or end < begin or site.count(WEB_BEGIN) != 1 or site.count(WEB_END) != 1:
        raise SystemExit(f"error: {WEB.name} needs its two score markers, once each, in order")
    return site[:begin] + scores + site[site.index("\n", end) + 1 :]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the page is not current")
    args = parser.parse_args(argv)
    store = results_store.Store.at(STORE)
    site = WEB.read_text(encoding="utf-8")
    written = {PAGE: page(store), WEB: with_scores(site, web_scores(store))}
    if args.check:
        stale = [
            path
            for path, text in written.items()
            if (path.read_text(encoding="utf-8") if path.is_file() else None) != text
        ]
        for path in stale:
            print(
                f"error: {_named(path)} is not what the results store gives: run "
                "uv run python scripts/scoreboard_page.py and commit it",
                file=sys.stderr,
            )
        if stale:
            return 1
        for path in written:
            print(f"ok  {_named(path)} is the store's")
        return 0
    for path, text in written.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {_named(path)}")
    return 0


def _named(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


if __name__ == "__main__":
    sys.exit(main())
