"""The early scoreboard's page (LP-17f; the grading method's section 14): writes
docs/grading/scoreboard.md from the results store (scoreboard/) and the repository's packs
(packs/, never `MENDARI_PACKS_PATH` or the registry cache) alone, so its bytes depend only on the
repository. It shows the current results (`results_store.heads`) one table
per pack and set (`scoreboard.board`, `render.scoreboard_markdown`): the scope statement, the
insufficient-evidence banner where it applies, the arms as measured, "not measured" or "not
applicable", and the marks "unsigned", "method draft, not in effect" and "stale after DATE" (or
why it is stale); then each superseded result, with the one that superseded it. No Rank column,
no bare percentage.

    uv run python scripts/scoreboard_page.py           # write the page
    uv run python scripts/scoreboard_page.py --check   # exit 1 when it is not the store's

CI's `reference-pack` job runs --check before scripts/build-reference-pack.sh, which writes the
page again (a pack change makes its results stale, and the page says so).
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Callable
from pathlib import Path

from mendari.core.pack import Pack
from mendari.evals import method, results_store, scoreboard
from mendari.evals.render import scoreboard_markdown

ROOT = Path(__file__).resolve().parent.parent
STORE = ROOT / results_store.ROOT
PACKS = ROOT / "packs"
PAGE = ROOT / "docs" / "grading" / "scoreboard.md"
TITLE = "# Scoreboard (public sets)"
GENERATED = (
    "<!-- Generated by scripts/scoreboard_page.py from the results store (scoreboard/): run it "
    "again rather than edit this page. -->"
)


def repository_pack(ref: str) -> Pack:
    """The pack `ref` names, from the repository's packs/ alone (`maintained_pack`)."""
    return results_store.maintained_pack(ref, PACKS)


def page(store: results_store.Store, packs: Callable[[str], Pack] = repository_pack) -> str:
    """The page's text: from the store's results and the packs they are of, nothing else."""
    results = store.results()
    current = results_store.heads(results)
    later = results_store.superseded(results)
    of = {found.pack_id: scoreboard.Current.of(packs(found.pack_id)) for found in current.values()}
    board = scoreboard.board([found.result for found in current.values()], of)
    signed = sum(found.signed for found in current.values())
    lines = [
        TITLE,
        "",
        GENERATED,
        "",
        "The early scoreboard (stage 3 of the [grading method](method-1.0.md), section 14): every "
        "local configuration of each reference pack, on each of its public scoring sets (its "
        "`test` set, its enriched set and that set's holdout). This page is generated from the "
        "results store, `scoreboard/` in the repository, and from nothing else, so the same "
        "store gives the same page ([running and checking the "
        "scoreboard](../operations/scoreboard.md)).",
        "",
        '!!! warning "Engineering evaluation, not clinical validation"',
        "    Every set here is public: it is in the repository and in the package, so anything "
        "can be tuned to it. Each table is a regression check, not a ranking. No figure orders "
        "its columns, and nothing here is graded: grades are given only on frozen hidden sets.",
        "",
        f"- **{_counted(len(current), 'current result')}** "
        f"({_counted(len(later), 'superseded result')} listed at the end), "
        f'{signed} signed. A result reads "{scoreboard.UNSIGNED}" until the owner signs it '
        "([verifying a result](verifying.md)).",
        f'- **"{scoreboard.DRAFT}":** the method has no effective date yet.',
        "- **Stale:** each result shows the day it goes stale, "
        f"{method.STALE_AFTER_DAYS} days after it was measured, "
        'as "stale after DATE". It reads "stale: pack changed", "stale: set changed" or "stale: '
        'method changed" when the pack, the set or the method is no longer the one it was '
        "measured on. A stale result is run again, never edited, and the new one supersedes it.",
        "- **Insufficient evidence:** a table whose critical label has fewer distinct positives "
        "than the method's minimum carries the banner, naming each such label.",
        "- **Not measured:** an arm, or a configuration of a measured arm, that no result covers "
        "yet. Only local configurations are run here.",
        "",
        scoreboard_markdown(board).rstrip("\n"),
        "",
        "## Superseded results",
        "",
    ]
    if not later:
        lines.append("None yet: no stored result has been superseded.")
    else:
        lines += [
            "Each stays in the store, as it was stored, and is no longer shown above.",
            "",
            "| Result | Superseded by | Pack, set and configuration | Measured on |",
            "|---|---|---|---|",
        ]
        for name, by in sorted(later.items()):
            found = results.get(name)  # the store's check refuses a link to no stored result
            what = ("not stored", "") if found is None else (found.shown, found.measured_on)
            lines.append(f"| `{name[:16]}` | `{by[:16]}` | {what[0]} | {what[1]} |")
    return "\n".join(lines) + "\n"


def _counted(count: int, what: str) -> str:
    return f"{count} {what}{'' if count == 1 else 's'}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the page is not current")
    args = parser.parse_args(argv)
    text = page(results_store.Store.at(STORE))
    shown = PAGE.relative_to(ROOT).as_posix()
    if args.check:
        held = PAGE.read_text(encoding="utf-8") if PAGE.is_file() else None
        if held != text:
            print(
                f"error: {shown} is not what the results store gives: run "
                "uv run python scripts/scoreboard_page.py and commit it",
                file=sys.stderr,
            )
            return 1
        print(f"ok  {shown} is the store's")
        return 0
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {shown}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
