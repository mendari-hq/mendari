"""US Core 6.1.0 checks for FHIR inputs, in process and without a terminology server.

What is checked comes from the official packages (`us_core_6_1_0.json`, generated by
`scripts/us_core_subset.py`): required elements, required bindings that can be enumerated,
required `category` slices, and the profiles' own `us-core-*` invariants. Deeper structure,
extensible bindings and terminology are left to the HL7 FHIR validator, which CI runs over the
sandbox's resources so that this subset cannot drift from the real profiles.

A profile is chosen by `meta.profile` when it names one of these, otherwise by resource type
(and category, for Condition, Observation and DiagnosticReport). Types US Core 6.1.0 does not
profile (MedicationStatement, Communication, non-laboratory Observations) get the base R4
checks. Issues never include values from the resource, only paths, so they can be logged and
returned without exposing patient data.
"""

from __future__ import annotations

import json
from collections.abc import Callable, Iterator, Mapping
from dataclasses import asdict, dataclass
from functools import cache
from pathlib import Path
from typing import Any, Literal

from openhealth.standards.fhir import iter_resources

DATA = Path(__file__).with_name("us_core_6_1_0.json")
US_CORE_VERSION = "6.1.0"
PROFILE_BASE = "http://hl7.org/fhir/us/core/StructureDefinition/"
DATA_ABSENT = "http://hl7.org/fhir/StructureDefinition/data-absent-reason"
UCUM = "http://unitsofmeasure.org"
SNOMED = "http://snomed.info/sct"
TERMINOLOGY = "http://terminology.hl7.org/CodeSystem"
_REPORTED = ("partial", "preliminary", "final", "amended", "corrected", "appended")
_ORDERS = ("order", "original-order", "reflex-order", "filler-order", "instance-order")

Severity = Literal["error", "warning"]
IssueCode = Literal["required", "code-invalid", "invariant"]


@dataclass(frozen=True)
class Issue:
    """One finding, shaped like an OperationOutcome issue."""

    severity: Severity
    code: IssueCode
    expression: str  # FHIRPath from the resource type, e.g. "Patient.identifier[0].system"
    diagnostics: str  # what is wrong, without the resource's values
    resource: str  # "Patient/p1", or "Patient" when the resource has no id
    profile: str  # the profile's canonical URL

    def to_dict(self) -> dict[str, str]:
        return asdict(self)


@cache
def profiles() -> dict[str, dict[str, Any]]:
    data: dict[str, Any] = json.loads(DATA.read_text(encoding="utf-8"))
    return data["profiles"]


def validate(resources: Any) -> list[Issue]:
    """Check every resource in a Bundle, a resource, a list or a CDS Hooks prefetch object."""
    issues: list[Issue] = []
    seen: set[tuple[str, str]] = set()
    for resource in iter_resources(resources):
        key = (str(resource.get("resourceType")), str(resource.get("id")))
        if resource.get("id") and key in seen:
            continue  # the same resource in two prefetch results is checked once
        seen.add(key)
        name = profile_for(resource)
        if name is not None:
            issues += check(resource, name)
    return issues


def errors(issues: list[Issue]) -> list[Issue]:
    return [issue for issue in issues if issue.severity == "error"]


def operation_outcome(issues: list[Issue]) -> dict[str, Any]:
    """The issues as a FHIR OperationOutcome (an empty one says "all OK", as FHIR requires)."""
    if not issues:
        return {
            "resourceType": "OperationOutcome",
            "issue": [{"severity": "information", "code": "informational", "diagnostics": "OK"}],
        }
    return {
        "resourceType": "OperationOutcome",
        "issue": [
            {
                "severity": issue.severity,
                "code": issue.code,
                "diagnostics": f"{issue.resource}: {issue.diagnostics}",
                "expression": [issue.expression],
            }
            for issue in issues
        ],
    }


def profile_for(resource: Mapping[str, Any]) -> str | None:
    kind = resource.get("resourceType")
    known = profiles()
    for url in (resource.get("meta") or {}).get("profile", []):
        name = str(url).split("|")[0].removeprefix(PROFILE_BASE)
        if name in known and known[name]["type"] == kind:
            return name
    categories = _codings(resource.get("category"))
    if kind == "Condition":
        encounter = (
            f"{TERMINOLOGY}/condition-category",
            "encounter-diagnosis",
        )
        return (
            "us-core-condition-encounter-diagnosis"
            if encounter in categories
            else "us-core-condition-problems-health-concerns"
        )
    if kind == "Observation":
        laboratory = (f"{TERMINOLOGY}/observation-category", "laboratory")
        return "us-core-observation-lab" if laboratory in categories else "base-observation"
    if kind == "DiagnosticReport":
        lab = (f"{TERMINOLOGY}/v2-0074", "LAB")
        return (
            "us-core-diagnosticreport-lab" if lab in categories else "us-core-diagnosticreport-note"
        )
    by_type = {profile["type"]: name for name, profile in known.items()}
    return by_type.get(str(kind))


def check(resource: Mapping[str, Any], name: str) -> list[Issue]:
    spec = profiles()[name]
    kind = spec["type"]
    label = f"{kind}/{resource['id']}" if resource.get("id") else kind
    found: list[Issue] = []

    def issue(code: IssueCode, expression: str, diagnostics: str) -> None:
        found.append(Issue("error", code, expression, diagnostics, label, spec["url"]))

    for path in spec["required"]:
        parent, _, child = path.rpartition(".")
        for where, item in _items(resource, parent, kind):
            if not _present(item, child):
                issue("required", f"{where}.{child}", f"{child} is required ({spec['title']})")
    for path, pairs in spec["codes"].items():
        allowed = {tuple(pair) for pair in pairs}
        codes = {code for _, code in allowed}
        systems = {system for system, _ in allowed}
        parent, _, child = path.rpartition(".")
        for where, item in _items(resource, parent, kind):
            for index, value in _values(item, child):
                at = f"{where}.{child}" + (f"[{index}]" if index is not None else "")
                if isinstance(value, str):
                    if value not in codes:
                        issue(
                            "code-invalid", at, f"{child} is not a code from its required value set"
                        )
                elif isinstance(value, Mapping):
                    ours = [c for c in _codings(value) if c[0] in systems]
                    if not ours or any(c not in allowed for c in ours):
                        issue(
                            "code-invalid", at, f"{child} needs a code from its required value set"
                        )
    for slice_ in spec["slices"]:
        allowed = {tuple(pair) for pair in slice_["codings"]}
        if not allowed & _codings(resource.get(slice_["path"])):
            issue(
                "required",
                f"{kind}.{slice_['path']}",
                f"{slice_['path']} needs the {slice_['name']} category ({spec['title']})",
            )
    for invariant in spec["invariants"]:
        rule = _INVARIANTS.get((spec["type"], invariant["key"]))
        if rule is None:
            continue
        for where in rule(resource, kind):
            issue("invariant", where, f"{invariant['key']}: {invariant['human']}")
    return found


# -- element navigation (the subset of FHIRPath the profiles' paths need) -----------------------


def _items(resource: Mapping[str, Any], path: str, kind: str) -> Iterator[tuple[str, Any]]:
    """(FHIRPath, value) for every present item at `path` ("" is the resource itself)."""
    current: list[tuple[str, Any]] = [(kind, resource)]
    for step in path.split(".") if path else []:
        following = []
        for where, item in current:
            for index, value in _values(item, step):
                following.append(
                    (f"{where}.{step}" + (f"[{index}]" if index is not None else ""), value)
                )
        current = following
    yield from current


def _values(item: Any, name: str) -> Iterator[tuple[int | None, Any]]:
    if not isinstance(item, Mapping):
        return
    if name.endswith("[x]"):
        stem = name[:-3]
        keys = [k for k in item if k.startswith(stem) and k[len(stem) : len(stem) + 1].isupper()]
        value = item[keys[0]] if keys else None
    else:
        value = item.get(name)
    if value is None:
        return
    if isinstance(value, list):
        yield from enumerate(value)
    else:
        yield None, value


def _present(item: Any, name: str) -> bool:
    return any(value not in ("", [], {}) for _, value in _values(item, name))


def _codings(value: Any) -> set[tuple[str, str]]:
    """(system, code) pairs of a CodeableConcept or a list of them."""
    concepts = value if isinstance(value, list) else [value]
    return {
        (str(coding.get("system")), str(coding.get("code")))
        for concept in concepts
        if isinstance(concept, Mapping)
        for coding in concept.get("coding", [])
        if isinstance(coding, Mapping)
    }


# -- the profiles' us-core-* invariants, by (type, key) -----------------------------------------

Rule = Callable[[Mapping[str, Any], str], list[str]]


def _patient_name(resource: Mapping[str, Any], kind: str) -> list[str]:
    bad = []
    for where, name in _items(resource, "name", kind):
        has_parts = bool(name.get("family") or name.get("given"))
        absent = any(e.get("url") == DATA_ABSENT for e in name.get("extension", []))
        if has_parts == absent:
            bad.append(where)
    return bad


def _attachment(resource: Mapping[str, Any], kind: str) -> list[str]:
    return [
        where
        for where, attachment in _items(resource, "content.attachment", kind)
        if not (attachment.get("url") or attachment.get("data"))
    ]


def _value_or_reason(resource: Mapping[str, Any], kind: str) -> list[str]:
    if resource.get("component") or resource.get("hasMember"):
        return []
    has_value = any(key.startswith("value") and key[5:6].isupper() for key in resource)
    return [] if has_value or resource.get("dataAbsentReason") else [kind]


def _full_date(resource: Mapping[str, Any], kind: str) -> list[str]:
    value = resource.get("effectiveDateTime")
    return [f"{kind}.effective"] if isinstance(value, str) and len(value) < 10 else []


def _ucum(resource: Mapping[str, Any], kind: str) -> list[str]:
    system = (resource.get("valueQuantity") or {}).get("system")
    return [f"{kind}.value"] if system not in (None, UCUM) else []


def _snomed_value(resource: Mapping[str, Any], kind: str) -> list[str]:
    systems = {system for system, _ in _codings(resource.get("valueCodeableConcept"))}
    return [f"{kind}.value"] if systems - {SNOMED, "None"} else []


def _reported_needs(element: str) -> Rule:
    def rule(resource: Mapping[str, Any], kind: str) -> list[str]:
        if resource.get("status") not in _REPORTED or _present(resource, element):
            return []
        return [f"{kind}.{element.removesuffix('[x]')}"]

    return rule


def _performed(resource: Mapping[str, Any], kind: str) -> list[str]:
    active = resource.get("status") in ("completed", "in-progress")
    return [f"{kind}.performed"] if active and not _present(resource, "performed[x]") else []


def _member_id(resource: Mapping[str, Any], kind: str) -> list[str]:
    member = (f"{TERMINOLOGY}/v2-0203", "MB")
    typed = any(member in _codings(i.get("type")) for i in resource.get("identifier", []))
    return [] if typed or resource.get("subscriberId") else [f"{kind}.identifier"]


def _requester(resource: Mapping[str, Any], kind: str) -> list[str]:
    ordered = resource.get("intent") in _ORDERS
    return [f"{kind}.requester"] if ordered and not resource.get("requester") else []


_INVARIANTS: dict[tuple[str, str], Rule] = {
    ("Patient", "us-core-6"): _patient_name,
    ("DocumentReference", "us-core-6"): _attachment,
    ("Observation", "us-core-1"): _full_date,
    ("Observation", "us-core-2"): _value_or_reason,
    ("Observation", "us-core-3"): _ucum,
    ("Observation", "us-core-4"): _snomed_value,
    ("DiagnosticReport", "us-core-8"): _reported_needs("effective[x]"),
    ("DiagnosticReport", "us-core-9"): _reported_needs("issued"),
    ("DiagnosticReport", "us-core-10"): _reported_needs("effective[x]"),
    ("Procedure", "us-core-7"): _performed,
    ("Coverage", "us-core-15"): _member_id,
    ("MedicationRequest", "us-core-21"): _requester,
}
